-- ============================================================================
-- REGISTRO ACADEMICO | Santa Cruz de la Sierra
-- Instituciones educativas y sus estudiantes (universitarios y escolares).
-- Es la fuente oficial: Rutabol-SCZ solo consulta si un estudiante existe y esta vigente
-- y guarda su propia referencia; no copia el registro completo.
-- Se ejecuta con: psql -v app_role=<rol> (lo hace bd/00_init_bases.sh).
-- ============================================================================
BEGIN;
CREATE SCHEMA academico;
SET LOCAL search_path TO academico, public;

CREATE TABLE institucion_educativa (
 id_institucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(180) NOT NULL,
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('secundaria','universitaria')),
 direccion TEXT,
 dominio_correo VARCHAR(254),                     -- dominio principal del correo institucional
 dominios_alternos TEXT[] NOT NULL DEFAULT '{}',  -- otros dominios validos (ej. upds.net.bo)
 estado VARCHAR(20) NOT NULL DEFAULT 'habilitada' CHECK(estado IN ('habilitada','deshabilitada')),
 UNIQUE(nombre,tipo)
);
CREATE TABLE estudiante (
 id_estudiante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_institucion BIGINT NOT NULL REFERENCES institucion_educativa(id_institucion),
 nombre_completo VARCHAR(160) NOT NULL,
 nivel VARCHAR(20) NOT NULL CHECK(nivel IN ('secundario','universitario')),
 rude VARCHAR(40) UNIQUE,
 codigo_institucional VARCHAR(70),
 correo_institucional VARCHAR(254),
 programa VARCHAR(160),                           -- carrera o curso
 estado VARCHAR(20) NOT NULL DEFAULT 'vigente' CHECK(estado IN ('vigente','inactivo','egresado')),
 CONSTRAINT ck_credencial_estudiante CHECK (
   (nivel='secundario' AND rude IS NOT NULL AND codigo_institucional IS NULL)
   OR (nivel='universitario' AND codigo_institucional IS NOT NULL AND correo_institucional IS NOT NULL AND rude IS NULL)
 ),
 UNIQUE(id_institucion,codigo_institucional)
);
CREATE UNIQUE INDEX uq_estudiante_correo ON estudiante(lower(correo_institucional));
CREATE INDEX ix_estudiante_institucion ON estudiante(id_institucion);

-- El nivel debe coincidir con el tipo de institucion y el correo con alguno de sus dominios.
CREATE FUNCTION validar_estudiante() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE i RECORD; dominio TEXT;
BEGIN
 SELECT tipo,dominio_correo,dominios_alternos INTO i FROM institucion_educativa WHERE id_institucion=NEW.id_institucion;
 IF (NEW.nivel='secundario' AND i.tipo<>'secundaria') OR (NEW.nivel='universitario' AND i.tipo<>'universitaria') THEN
  RAISE EXCEPTION 'Nivel estudiantil incompatible con tipo de institucion';
 END IF;
 IF NEW.nivel='universitario' AND i.dominio_correo IS NOT NULL THEN
  dominio := lower(split_part(NEW.correo_institucional,'@',2));
  IF dominio<>lower(ltrim(i.dominio_correo,'@')) AND NOT dominio = ANY(i.dominios_alternos) THEN
   RAISE EXCEPTION 'Correo institucional no corresponde al dominio registrado';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tg_validar_estudiante BEFORE INSERT OR UPDATE OF id_institucion,nivel,correo_institucional ON estudiante
FOR EACH ROW EXECUTE FUNCTION validar_estudiante();

-- Rutabol administra las instituciones; los estudiantes solo se consultan (los carga cada institucion).
GRANT USAGE ON SCHEMA academico TO :"app_role";
GRANT SELECT,INSERT,UPDATE ON institucion_educativa TO :"app_role";
GRANT SELECT ON estudiante TO :"app_role";
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA academico TO :"app_role";
COMMIT;
