-- DINERO (SECURITY DEFINER): el backend decide tarifa y cobro; la base lo REGISTRA de forma idempotente
-- y protege el saldo (nunca negativo). La app no puede editar saldos ni insertar pagos directamente.
CREATE FUNCTION registrar_movimiento(p JSONB) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = rutabol, pg_temp AS $$
DECLARE t RECORD; ex RECORD; m BIGINT; r BIGINT;
        v_ref TEXT := p->>'ref'; v_tipo TEXT := p->>'tipo'; v_estado TEXT := p->>'estado';
        v_monto NUMERIC := (p->>'monto')::numeric; v_nuevo NUMERIC;
BEGIN
 IF v_ref IS NULL OR length(trim(v_ref))=0 THEN RAISE EXCEPTION 'Referencia requerida'; END IF;
 IF v_estado NOT IN ('confirmado','pendiente','rechazado') THEN RAISE EXCEPTION 'Estado de movimiento invalido'; END IF;
 SELECT tj.id_tarjeta,tj.saldo INTO t FROM tarjeta_credicard tj JOIN usuario u ON u.id_usuario=tj.id_usuario
  WHERE u.identificador=p->>'usuario' AND tj.estado<>'cancelada' FOR UPDATE OF tj;
 IF NOT FOUND THEN RAISE EXCEPTION 'Tarjeta inexistente'; END IF;
 SELECT id_movimiento,id_tarjeta,monto INTO ex FROM movimiento_saldo WHERE referencia=v_ref;
 IF FOUND THEN
  IF ex.id_tarjeta<>t.id_tarjeta OR ex.monto<>v_monto THEN RAISE EXCEPTION 'Referencia reutilizada para otro movimiento'; END IF;
  RETURN ex.id_movimiento;
 END IF;
 v_nuevo := t.saldo + CASE WHEN v_estado='confirmado' THEN v_monto ELSE 0 END;
 IF v_nuevo<0 THEN RAISE EXCEPTION 'Saldo insuficiente'; END IF;
 IF v_tipo='recarga' THEN
  INSERT INTO recarga(id_tarjeta,monto,fecha,canal,referencia,estado,clave_cliente,nota)
  VALUES(t.id_tarjeta,v_monto,to_timestamp((p->>'fecha')::numeric/1000.0),coalesce(p->>'canal','desconocido'),v_ref,
         CASE v_estado WHEN 'confirmado' THEN 'confirmada' WHEN 'pendiente' THEN 'pendiente' ELSE 'fallida' END,
         p->>'clave_cliente',p->>'nota') RETURNING id_recarga INTO r;
 END IF;
 INSERT INTO movimiento_saldo(id_tarjeta,tipo,monto,estado,referencia,motivo,saldo_posterior,id_recarga,fecha)
 VALUES(t.id_tarjeta,v_tipo,v_monto,v_estado,v_ref,p->>'motivo',v_nuevo,r,to_timestamp((p->>'fecha')::numeric/1000.0))
 RETURNING id_movimiento INTO m;
 IF v_estado='confirmado' THEN UPDATE tarjeta_credicard SET saldo=v_nuevo WHERE id_tarjeta=t.id_tarjeta; END IF;
 RETURN m;
END $$;

-- Resuelve un movimiento pendiente (recarga en proceso). Idempotente si ya tiene ese estado.
CREATE FUNCTION resolver_movimiento(p_ref TEXT,p_estado TEXT,p_nota TEXT DEFAULT NULL) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = rutabol, pg_temp AS $$
DECLARE m RECORD; t RECORD; v_nuevo NUMERIC;
BEGIN
 IF p_estado NOT IN ('confirmado','rechazado') THEN RAISE EXCEPTION 'Estado de resolucion invalido'; END IF;
 SELECT * INTO m FROM movimiento_saldo WHERE referencia=p_ref FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Movimiento inexistente'; END IF;
 IF m.estado=p_estado THEN RETURN m.id_movimiento; END IF;
 IF m.estado<>'pendiente' THEN RAISE EXCEPTION 'El movimiento ya fue resuelto como %',m.estado; END IF;
 SELECT saldo INTO t FROM tarjeta_credicard WHERE id_tarjeta=m.id_tarjeta FOR UPDATE;
 v_nuevo := t.saldo + CASE WHEN p_estado='confirmado' THEN m.monto ELSE 0 END;
 IF v_nuevo<0 THEN RAISE EXCEPTION 'Saldo insuficiente'; END IF;
 IF p_estado='confirmado' THEN UPDATE tarjeta_credicard SET saldo=v_nuevo WHERE id_tarjeta=m.id_tarjeta; END IF;
 UPDATE movimiento_saldo SET estado=p_estado,saldo_posterior=v_nuevo WHERE id_movimiento=m.id_movimiento;
 IF m.id_recarga IS NOT NULL THEN
  UPDATE recarga SET estado=CASE p_estado WHEN 'confirmado' THEN 'confirmada' ELSE 'fallida' END,
         nota=coalesce(p_nota,nota) WHERE id_recarga=m.id_recarga;
 END IF;
 RETURN m.id_movimiento;
END $$;

-- Registra (o actualiza el estado de) un pasaje cobrado por el backend. Idempotente por ref.
CREATE FUNCTION registrar_ticket(p JSONB) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = rutabol, pg_temp AS $$
DECLARE v_ref TEXT := p->>'ref'; v_metodo TEXT := p->>'metodo';
        v_fecha TIMESTAMPTZ := to_timestamp((p->>'fecha')::numeric/1000.0);
        u BIGINT; tj BIGINT; un BIGINT; ud BIGINT; tf BIGINT; v_id BIGINT;
BEGIN
 IF v_ref IS NULL OR length(trim(v_ref))=0 THEN RAISE EXCEPTION 'Referencia requerida'; END IF;
 SELECT ut.id_unidad INTO un FROM unidad_transporte ut JOIN linea l ON l.id_linea=ut.id_linea
  WHERE l.numero=p->>'linea' AND ut.numero_interno=p->>'interno';
 IF NOT FOUND THEN RAISE EXCEPTION 'Unidad inexistente'; END IF;
 IF p->>'linea_destino' IS NOT NULL THEN
  SELECT ut.id_unidad INTO ud FROM unidad_transporte ut JOIN linea l ON l.id_linea=ut.id_linea
   WHERE l.numero=p->>'linea_destino' AND ut.numero_interno=p->>'interno_destino';
  IF NOT FOUND THEN RAISE EXCEPTION 'Unidad de destino inexistente'; END IF;
 END IF;
 IF p->>'usuario' IS NOT NULL THEN
  SELECT id_usuario INTO u FROM usuario WHERE identificador=p->>'usuario';
  IF NOT FOUND THEN RAISE EXCEPTION 'Usuario inexistente'; END IF;
 END IF;
 IF v_metodo='credicard' THEN
  SELECT id_tarjeta INTO tj FROM tarjeta_credicard WHERE id_usuario=u AND estado<>'cancelada';
  IF NOT FOUND THEN RAISE EXCEPTION 'Tarjeta inexistente'; END IF;
 END IF;
 SELECT ta.id_tarifa INTO tf FROM tarifa ta JOIN categoria_pasajero cp ON cp.id_categoria=ta.id_categoria
  WHERE cp.nombre=p->>'categoria' AND ta.vigente_desde<=v_fecha ORDER BY ta.vigente_desde DESC LIMIT 1;
 IF NOT FOUND THEN
  SELECT ta.id_tarifa INTO tf FROM tarifa ta JOIN categoria_pasajero cp ON cp.id_categoria=ta.id_categoria
   WHERE cp.nombre=p->>'categoria' ORDER BY ta.vigente_desde LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'No hay tarifa para %',p->>'categoria'; END IF;
 END IF;
 INSERT INTO transaccion_pago(ref_app,id_tarjeta,id_usuario,id_unidad,id_unidad_destino,id_tarifa,metodo,monto,fecha,
                              razon_tarifa,categoria,numero_comprobante,clave_idempotencia,clave_cliente,
                              estado_abordaje,codigo_pase,abordado_en)
 VALUES(v_ref,tj,u,un,ud,tf,v_metodo,(p->>'monto')::numeric,v_fecha,p->>'razon',p->>'categoria',p->>'comprobante',
        v_ref,p->>'clave_cliente',p->>'estado_abordaje',p->>'codigo_pase',
        CASE WHEN p->>'estado_abordaje'='abordado' THEN now() END)
 ON CONFLICT (ref_app) DO UPDATE SET estado_abordaje=EXCLUDED.estado_abordaje,
   id_unidad_destino=EXCLUDED.id_unidad_destino,codigo_pase=EXCLUDED.codigo_pase,
   abordado_en=coalesce(transaccion_pago.abordado_en,EXCLUDED.abordado_en)
 RETURNING id_transaccion INTO v_id;
 RETURN v_id;
END $$;


