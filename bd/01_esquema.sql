-- ============================================================================
-- RUTABOL-SCZ | PostgreSQL 14+ | Modelo relacional v2
-- Requisitos: haber ejecutado 00_setup.sql y estar conectado a rutabol_scz como rutabol_owner.
-- Seguro: aborta sin tocar nada si el esquema "rutabol" ya tiene tablas.
-- Roles de la app: control (Centro de Control), chofer, pasajero. El beneficio estudiantil
-- se deriva de la validacion aprobada (solicitud_validacion), no de un rol aparte.
-- Credicard = saldo interno; una pasarela real requiere integracion externa.
-- ============================================================================
BEGIN;

DO $$ BEGIN
 IF current_user <> 'rutabol_owner' THEN
  RAISE EXCEPTION 'Ejecuta este script conectado como rutabol_owner (ahora: %)', current_user;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='rutabol_app') THEN
  RAISE EXCEPTION 'Falta el rol rutabol_app: ejecuta primero 00_setup.sql';
 END IF;
 IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='rutabol') THEN
  RAISE EXCEPTION 'El esquema rutabol ya tiene tablas; este script solo crea desde cero';
 END IF;
END $$;

CREATE SCHEMA IF NOT EXISTS rutabol;
SET LOCAL search_path TO rutabol, public;

-- 1. IDENTIDAD Y SEGURIDAD
CREATE TABLE usuario (
 id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre_completo VARCHAR(160) NOT NULL,
 ci VARCHAR(30) UNIQUE,                      -- opcional: el registro actual no lo pide
 correo VARCHAR(254),
 identificador VARCHAR(200) NOT NULL UNIQUE,   -- id de acceso en el backend (minusculas)
 codigo VARCHAR(200),                          -- CI/RUDE/codigo universitario, o interno del chofer
 foto TEXT,
 categoria VARCHAR(15) CHECK (categoria IN ('general','escolar','universitario')),
 telefono VARCHAR(30),
 password_hash TEXT NOT NULL,
 estado VARCHAR(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','suspendido','inactivo')),
 acepto_terminos_en TIMESTAMPTZ,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_usuario_correo_lower ON usuario (lower(correo));
CREATE TABLE rol (
 id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(40) NOT NULL UNIQUE,
 descripcion TEXT
);
CREATE TABLE permiso (
 id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(90) NOT NULL UNIQUE,
 descripcion TEXT
);
CREATE TABLE usuario_rol (
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
 id_rol BIGINT NOT NULL REFERENCES rol(id_rol) ON DELETE CASCADE,
 PRIMARY KEY(id_usuario,id_rol)
);
CREATE TABLE rol_permiso (
 id_rol BIGINT NOT NULL REFERENCES rol(id_rol) ON DELETE CASCADE,
 id_permiso BIGINT NOT NULL REFERENCES permiso(id_permiso) ON DELETE CASCADE,
 PRIMARY KEY(id_rol,id_permiso)
);
CREATE TABLE sesion (
 id_sesion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
 token_hash TEXT NOT NULL UNIQUE,            -- nunca el token en claro
 agente VARCHAR(250),
 creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 ultimo_uso TIMESTAMPTZ NOT NULL DEFAULT now(),
 expira_en TIMESTAMPTZ NOT NULL,
 revocada_en TIMESTAMPTZ
);
CREATE TABLE recuperacion_clave (
 id_recuperacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
 token_hash TEXT NOT NULL UNIQUE,
 expiracion TIMESTAMPTZ NOT NULL,
 intentos INTEGER NOT NULL DEFAULT 0 CHECK(intentos>=0),
 utilizado BOOLEAN NOT NULL DEFAULT false,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE credencial_qr (                  -- QR firmado de abordaje: 60 s, un solo uso
 id_credencial VARCHAR(64) PRIMARY KEY,
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
 expira_en TIMESTAMPTZ NOT NULL,
 usado_en TIMESTAMPTZ
);

-- 2. VALIDACION ESTUDIANTIL
CREATE TABLE institucion_educativa (
 id_institucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(180) NOT NULL,
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('secundaria','universitaria')),
 direccion TEXT,
 dominio_correo VARCHAR(254),
 estado VARCHAR(20) NOT NULL DEFAULT 'habilitada' CHECK(estado IN ('habilitada','deshabilitada')),
 UNIQUE(nombre,tipo)
);
CREATE TABLE estudiante (
 id_estudiante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario),
 id_institucion BIGINT NOT NULL REFERENCES institucion_educativa(id_institucion),
 nivel VARCHAR(20) NOT NULL CHECK(nivel IN ('secundario','universitario')),
 rude VARCHAR(40) UNIQUE,
 codigo_institucional VARCHAR(70),
 correo_institucional VARCHAR(254),
 foto_url TEXT,
 CONSTRAINT ck_credencial_estudiante CHECK (
   (nivel='secundario' AND rude IS NOT NULL AND codigo_institucional IS NULL)
   OR (nivel='universitario' AND codigo_institucional IS NOT NULL AND correo_institucional IS NOT NULL AND rude IS NULL)
 ),
 UNIQUE(id_institucion,codigo_institucional)
);
CREATE TABLE solicitud_validacion (
 id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_estudiante BIGINT NOT NULL REFERENCES estudiante(id_estudiante),
 fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT now(),
 estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
   CHECK(estado IN ('pendiente','aprobada','observada','rechazada','vencida','revocada')),
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 correo_verificado BOOLEAN NOT NULL DEFAULT false,
 fecha_resolucion TIMESTAMPTZ,
 id_revisor BIGINT REFERENCES usuario(id_usuario),
 nota TEXT,                                   -- motivo de rechazo u observacion
 vigencia_hasta TIMESTAMPTZ,
 CONSTRAINT ck_resolucion_validacion CHECK (
   (estado='pendiente' AND fecha_resolucion IS NULL) OR (estado<>'pendiente' AND fecha_resolucion IS NOT NULL))
);
CREATE UNIQUE INDEX uq_solicitud_pendiente ON solicitud_validacion(id_estudiante) WHERE estado='pendiente';
CREATE UNIQUE INDEX uq_solicitud_aprobada ON solicitud_validacion(id_estudiante) WHERE estado='aprobada';

-- 3. TRANSPORTE
CREATE TABLE conductor (
 id_conductor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario),
 licencia VARCHAR(50) UNIQUE,                 -- opcional hasta que el Centro de Control capture RF-06
 categoria_licencia VARCHAR(30),
 foto_url TEXT,
 habilitado BOOLEAN NOT NULL DEFAULT false,
 licencia_vigente_hasta DATE
);
CREATE TABLE linea (
 id_linea BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(120) NOT NULL,
 estado VARCHAR(20) NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','inactiva'))
);
CREATE TABLE ruta (
 id_ruta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_linea BIGINT NOT NULL REFERENCES linea(id_linea),
 nombre VARCHAR(120) NOT NULL,
 origen VARCHAR(180) NOT NULL,
 destino VARCHAR(180) NOT NULL,
 sentido VARCHAR(30) NOT NULL CHECK(sentido IN ('ida','vuelta','circular')),
 estado VARCHAR(20) NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','inactiva')),
 UNIQUE(id_linea,nombre,sentido)
);
CREATE TABLE punto_ruta (
 id_punto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_ruta BIGINT NOT NULL REFERENCES ruta(id_ruta) ON DELETE CASCADE,
 orden INTEGER NOT NULL CHECK(orden>0),
 latitud NUMERIC(10,7) NOT NULL CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(10,7) NOT NULL CHECK(longitud BETWEEN -180 AND 180),
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('inicio','parada','referencia','destino')),
 descripcion VARCHAR(250),
 UNIQUE(id_ruta,orden)
);
CREATE TABLE unidad_transporte (
 id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_linea BIGINT NOT NULL REFERENCES linea(id_linea),
 numero_interno VARCHAR(35) NOT NULL,          -- unico por linea (el backend identifica la unidad como linea-interno)
 placa VARCHAR(20) NOT NULL UNIQUE,
 marca VARCHAR(70), modelo VARCHAR(70),
 capacidad_maxima INTEGER NOT NULL CHECK(capacidad_maxima>0),
 estado VARCHAR(25) NOT NULL DEFAULT 'habilitada'
   CHECK(estado IN ('habilitada','deshabilitada','mantenimiento','fuera_servicio')),
 estado_operativo VARCHAR(20) NOT NULL DEFAULT 'activo'
   CHECK(estado_operativo IN ('activo','descanso','emergencia')),
 CONSTRAINT uq_unidad_linea_interno UNIQUE(id_linea,numero_interno)
);
CREATE TABLE asignacion_conductor (
 id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_conductor BIGINT NOT NULL REFERENCES conductor(id_conductor),
 id_unidad BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT now(),
 fecha_fin TIMESTAMPTZ,
 estado VARCHAR(20) NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','finalizada','cancelada')),
 CHECK(fecha_fin IS NULL OR fecha_fin>=fecha_inicio),
 CHECK(estado<>'activa' OR fecha_fin IS NULL)
);
CREATE UNIQUE INDEX uq_asignacion_unidad_activa ON asignacion_conductor(id_unidad) WHERE estado='activa';
CREATE UNIQUE INDEX uq_asignacion_conductor_activo ON asignacion_conductor(id_conductor) WHERE estado='activa';

-- 4. TARIFAS Y PAGOS
CREATE TABLE categoria_pasajero (
 id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(40) NOT NULL UNIQUE,          -- general | escolar | universitario (igual que el backend)
 descripcion TEXT
);
CREATE TABLE tarifa (
 id_tarifa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_categoria BIGINT NOT NULL REFERENCES categoria_pasajero(id_categoria),
 monto NUMERIC(12,2) NOT NULL CHECK(monto>=0),
 vigente_desde TIMESTAMPTZ NOT NULL,
 vigente_hasta TIMESTAMPTZ,
 CHECK(vigente_hasta IS NULL OR vigente_hasta>vigente_desde)
);
CREATE UNIQUE INDEX uq_tarifa_abierta ON tarifa(id_categoria) WHERE vigente_hasta IS NULL;
CREATE TABLE tarjeta_credicard (
 id_tarjeta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
 identificador VARCHAR(100) NOT NULL UNIQUE,
 tarjeta_fisica VARCHAR(100),                   -- solo los ultimos 4 digitos
 saldo NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(saldo>=0),
 estado VARCHAR(20) NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','bloqueada','cancelada')),
 creada_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_tarjeta_usuario_vigente ON tarjeta_credicard(id_usuario) WHERE estado<>'cancelada';
CREATE TABLE recarga (
 id_recarga BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_tarjeta BIGINT NOT NULL REFERENCES tarjeta_credicard(id_tarjeta),
 monto NUMERIC(12,2) NOT NULL CHECK(monto>0),
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 canal VARCHAR(40) NOT NULL,
 referencia VARCHAR(120) NOT NULL UNIQUE,     -- clave de idempotencia de la recarga
 estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK(estado IN ('pendiente','confirmada','fallida')),
 clave_cliente VARCHAR(200),                  -- clave de idempotencia que envia el cliente
 nota TEXT
);
CREATE UNIQUE INDEX uq_recarga_clave_cliente ON recarga(id_tarjeta,clave_cliente) WHERE clave_cliente IS NOT NULL;
-- Libro de saldo: monto con signo (+ recarga/devolucion, - pasaje, +/- ajuste)
CREATE TABLE movimiento_saldo (
 id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_tarjeta BIGINT NOT NULL REFERENCES tarjeta_credicard(id_tarjeta),
 tipo VARCHAR(12) NOT NULL CHECK(tipo IN ('recarga','pasaje','ajuste','devolucion')),
 monto NUMERIC(14,2) NOT NULL,
 estado VARCHAR(12) NOT NULL DEFAULT 'confirmado' CHECK(estado IN ('confirmado','pendiente','rechazado')),
 referencia VARCHAR(120) NOT NULL UNIQUE,
 motivo TEXT,
 saldo_posterior NUMERIC(14,2) NOT NULL CHECK(saldo_posterior>=0),
 id_recarga BIGINT REFERENCES recarga(id_recarga),
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((tipo IN ('recarga','devolucion') AND monto>0) OR (tipo='pasaje' AND monto<0) OR (tipo='ajuste' AND monto<>0))
);

-- 5. VIAJES, GPS, OCUPACION E INCIDENCIAS
CREATE TABLE viaje (
 id_viaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_ruta BIGINT NOT NULL REFERENCES ruta(id_ruta),
 id_asignacion BIGINT NOT NULL REFERENCES asignacion_conductor(id_asignacion),
 fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT now(),
 fecha_fin TIMESTAMPTZ,
 estado VARCHAR(20) NOT NULL DEFAULT 'activo' CHECK(estado IN ('activo','finalizado','interrumpido','cancelado')),
 CHECK(fecha_fin IS NULL OR fecha_fin>=fecha_inicio),
 CHECK(estado<>'activo' OR fecha_fin IS NULL)
);
CREATE UNIQUE INDEX uq_viaje_asignacion_activo ON viaje(id_asignacion) WHERE estado='activo';
CREATE TABLE ubicacion_gps (
 id_ubicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_viaje BIGINT NOT NULL REFERENCES viaje(id_viaje),
 latitud NUMERIC(10,7) NOT NULL CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(10,7) NOT NULL CHECK(longitud BETWEEN -180 AND 180),
 fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
 precision_m NUMERIC(9,2) CHECK(precision_m>=0)
);
CREATE TABLE registro_ocupacion (            -- por unidad; el viaje es opcional
 id_ocupacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_unidad BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 id_viaje BIGINT REFERENCES viaje(id_viaje),
 tipo VARCHAR(12) NOT NULL CHECK(tipo IN ('subida','bajada','correccion')),
 ocupacion_anterior INTEGER NOT NULL CHECK(ocupacion_anterior>=0),
 ocupacion_resultante INTEGER NOT NULL CHECK(ocupacion_resultante>=0),
 motivo TEXT,
 id_usuario BIGINT REFERENCES usuario(id_usuario),
 fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(tipo<>'correccion' OR (motivo IS NOT NULL AND length(trim(motivo))>0))
);
CREATE TABLE incidencia (
 id_incidencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_unidad BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 id_viaje BIGINT REFERENCES viaje(id_viaje),          -- nulo si se reporta fuera de jornada
 id_reportante BIGINT REFERENCES usuario(id_usuario),
 tipo VARCHAR(30) NOT NULL CHECK(tipo IN ('falla_mecanica','accidente','problema_tecnico','emergencia','bloqueo','averia','otra')),
 severidad VARCHAR(10) NOT NULL DEFAULT 'media' CHECK(severidad IN ('alta','media','baja')),
 descripcion TEXT NOT NULL,
 latitud NUMERIC(10,7) CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(10,7) CHECK(longitud BETWEEN -180 AND 180),
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 estado VARCHAR(20) NOT NULL DEFAULT 'reportada' CHECK(estado IN ('reportada','en_atencion','resuelta','cerrada'))
);
CREATE TABLE historial_incidencia (
 id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_incidencia BIGINT NOT NULL REFERENCES incidencia(id_incidencia),
 estado VARCHAR(20) NOT NULL,
 id_usuario BIGINT REFERENCES usuario(id_usuario),
 fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE alerta (
 id_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_unidad BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 tipo VARCHAR(12) NOT NULL CHECK(tipo IN ('emergencia','aforo','incidente')),
 mensaje TEXT NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 atendida_en TIMESTAMPTZ
);
CREATE TABLE transaccion_pago (                 -- por unidad; el viaje es opcional
 id_transaccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_tarjeta BIGINT REFERENCES tarjeta_credicard(id_tarjeta),   -- nulo en efectivo
 id_usuario BIGINT REFERENCES usuario(id_usuario),             -- nulo si paga en efectivo sin cuenta
 id_viaje BIGINT REFERENCES viaje(id_viaje),
 id_tarifa BIGINT NOT NULL REFERENCES tarifa(id_tarifa),
 metodo VARCHAR(10) NOT NULL DEFAULT 'credicard' CHECK(metodo IN ('credicard','efectivo')),
 monto NUMERIC(12,2) NOT NULL CHECK(monto>=0),
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 estado VARCHAR(20) NOT NULL DEFAULT 'confirmada' CHECK(estado IN ('confirmada','reversada')),
 razon_tarifa TEXT,
 numero_comprobante VARCHAR(20) NOT NULL UNIQUE,
 clave_idempotencia VARCHAR(120) NOT NULL UNIQUE,
 abordado_en TIMESTAMPTZ,                                      -- el chofer valido el abordaje
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_unidad BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 id_unidad_destino BIGINT REFERENCES unidad_transporte(id_unidad),
 categoria VARCHAR(15) NOT NULL CHECK(categoria IN ('general','escolar','universitario')),
 estado_abordaje VARCHAR(15) NOT NULL DEFAULT 'pagado'
   CHECK(estado_abordaje IN ('pagado','abordado','rechazado','pase_temporal')),
 codigo_pase VARCHAR(40),
 clave_cliente VARCHAR(200),
 CHECK(metodo<>'credicard' OR id_tarjeta IS NOT NULL)
);
CREATE UNIQUE INDEX uq_pago_clave_cliente ON transaccion_pago(id_usuario,clave_cliente) WHERE clave_cliente IS NOT NULL;
CREATE SEQUENCE seq_comprobante;

-- 6. TRASBORDOS ("micro que descansa mantiene los pagos")
CREATE TABLE trasbordo (
 id_trasbordo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 motivo VARCHAR(12) NOT NULL CHECK(motivo IN ('incidencia','descanso')),
 id_incidencia BIGINT REFERENCES incidencia(id_incidencia),
 id_unidad_origen BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 id_unidad_destino BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 id_autorizador BIGINT REFERENCES usuario(id_usuario),
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 pasajeros INTEGER NOT NULL DEFAULT 0 CHECK(pasajeros>=0),
 monto_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(monto_total>=0),
 acreditado_a VARCHAR(10) CHECK(acreditado_a IN ('descanso','saliente')),
 estado VARCHAR(20) NOT NULL DEFAULT 'completado' CHECK(estado IN ('autorizado','completado','cancelado')),
 CHECK(id_unidad_origen<>id_unidad_destino)
);
CREATE TABLE pase_temporal (                   -- pase que el pasajero canjea en la unidad de reemplazo
 id_pase BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 codigo VARCHAR(40) NOT NULL UNIQUE,
 id_unidad_origen BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 id_unidad_destino BIGINT NOT NULL REFERENCES unidad_transporte(id_unidad),
 expira_en TIMESTAMPTZ NOT NULL,
 usado_en TIMESTAMPTZ
);

-- 7. CONTROL Y AUDITORIA
CREATE TABLE notificacion (
 id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
 tipo VARCHAR(50) NOT NULL,
 titulo VARCHAR(160) NOT NULL,
 mensaje TEXT NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 leida BOOLEAN NOT NULL DEFAULT false
);
CREATE TABLE reclamo (
 id_reclamo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_usuario BIGINT REFERENCES usuario(id_usuario),
 id_linea BIGINT REFERENCES linea(id_linea),
 id_unidad BIGINT REFERENCES unidad_transporte(id_unidad),
 id_viaje BIGINT REFERENCES viaje(id_viaje),
 id_transaccion BIGINT REFERENCES transaccion_pago(id_transaccion),
 tipo VARCHAR(30) NOT NULL DEFAULT 'otra'
   CHECK(tipo IN ('cobro_excesivo','tarifa_negada','sobresaturacion','mal_servicio','recorrido','otra')),
 descripcion TEXT NOT NULL,
 evidencia TEXT,
 fecha_hecho TIMESTAMPTZ,
 fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 estado VARCHAR(20) NOT NULL DEFAULT 'recibido' CHECK(estado IN ('recibido','en_revision','resuelto','rechazado')),
 respuesta TEXT,
 monto_reembolso NUMERIC(12,2) CHECK(monto_reembolso IS NULL OR monto_reembolso>=0),
 contacto_publico VARCHAR(254)
);
CREATE TABLE seguimiento_reclamo (
 id_seguimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_reclamo BIGINT NOT NULL REFERENCES reclamo(id_reclamo),
 id_administrador BIGINT NOT NULL REFERENCES usuario(id_usuario),
 estado_nuevo VARCHAR(20),
 accion TEXT NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE auditoria (                       -- solo anexado: ver tg_auditoria_*
 id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_app VARCHAR(40) NOT NULL UNIQUE,
 id_usuario BIGINT REFERENCES usuario(id_usuario),
 rol_actor VARCHAR(20),
 entidad VARCHAR(100) NOT NULL,
 id_registro BIGINT,
 accion VARCHAR(50) NOT NULL,
 objetivo TEXT,
 resultado VARCHAR(10) NOT NULL DEFAULT 'ok' CHECK(resultado IN ('ok','error')),
 detalle JSONB,
 fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);

