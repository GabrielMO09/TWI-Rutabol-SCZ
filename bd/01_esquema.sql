-- VALIDACIONES TRANSVERSALES (triggers: se ejecutan con los permisos de quien escribe)
CREATE FUNCTION validar_estudiante() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE t VARCHAR(20); dominio VARCHAR(254);
BEGIN
 SELECT tipo,dominio_correo INTO t,dominio FROM institucion_educativa WHERE id_institucion=NEW.id_institucion;
 IF (NEW.nivel='secundario' AND t<>'secundaria') OR (NEW.nivel='universitario' AND t<>'universitaria') THEN
  RAISE EXCEPTION 'Nivel estudiantil incompatible con tipo de institucion';
 END IF;
 IF NEW.nivel='universitario' AND dominio IS NOT NULL AND
    lower(split_part(NEW.correo_institucional,'@',2))<>lower(ltrim(dominio,'@')) THEN
  RAISE EXCEPTION 'Correo institucional no corresponde al dominio registrado';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tg_validar_estudiante BEFORE INSERT OR UPDATE OF id_institucion,nivel,correo_institucional ON estudiante
FOR EACH ROW EXECUTE FUNCTION validar_estudiante();

-- RN-04: el beneficio universitario exige correo institucional verificado
CREATE FUNCTION validar_solicitud() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE n VARCHAR(20);
BEGIN
 IF NEW.estado='aprobada' THEN
  SELECT nivel INTO n FROM estudiante WHERE id_estudiante=NEW.id_estudiante;
  IF n='universitario' AND NOT NEW.correo_verificado THEN
   RAISE EXCEPTION 'Correo institucional sin verificar: no se puede aprobar';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tg_validar_solicitud BEFORE INSERT OR UPDATE OF estado,correo_verificado ON solicitud_validacion
FOR EACH ROW EXECUTE FUNCTION validar_solicitud();

CREATE FUNCTION validar_viaje() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a RECORD; l BIGINT;
BEGIN
 SELECT ac.estado AS estado_asignacion,c.habilitado,c.licencia_vigente_hasta,
        u.estado AS estado_unidad,u.id_linea,us.estado AS estado_usuario
 INTO a FROM asignacion_conductor ac
 JOIN conductor c ON c.id_conductor=ac.id_conductor
 JOIN usuario us ON us.id_usuario=c.id_usuario
 JOIN unidad_transporte u ON u.id_unidad=ac.id_unidad
 WHERE ac.id_asignacion=NEW.id_asignacion;
 SELECT id_linea INTO l FROM ruta WHERE id_ruta=NEW.id_ruta;
 IF NOT FOUND OR a.estado_asignacion IS DISTINCT FROM 'activa' OR NOT a.habilitado OR a.estado_unidad<>'habilitada'
    OR a.estado_usuario<>'activo' OR a.id_linea<>l
    OR (a.licencia_vigente_hasta IS NOT NULL AND a.licencia_vigente_hasta<CURRENT_DATE) THEN
  RAISE EXCEPTION 'Viaje no autorizado: asignacion, conductor, unidad o linea invalidos';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tg_validar_viaje BEFORE INSERT OR UPDATE OF id_ruta,id_asignacion ON viaje
FOR EACH ROW EXECUTE FUNCTION validar_viaje();

