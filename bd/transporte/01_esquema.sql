-- ============================================================================
-- REGISTRO DE TRANSPORTE | Santa Cruz de la Sierra
-- Informacion oficial de lineas, rutas, recorridos, paradas y unidades.
-- Base propia: Rutabol-SCZ la consulta y mantiene al dia a traves de su rol de aplicacion.
-- Se ejecuta con: psql -v app_role=<rol> (lo hace bd/00_init_bases.sh).
-- ============================================================================
BEGIN;
CREATE SCHEMA transporte;
SET LOCAL search_path TO transporte, public;

CREATE TABLE linea (
 id_linea BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(120) NOT NULL,
 estado VARCHAR(20) NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','inactiva'))
);
CREATE TABLE ruta (                              -- recorrido oficial de una linea
 id_ruta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_linea BIGINT NOT NULL REFERENCES linea(id_linea),
 nombre VARCHAR(120) NOT NULL,
 origen VARCHAR(180) NOT NULL,
 destino VARCHAR(180) NOT NULL,
 sentido VARCHAR(30) NOT NULL CHECK(sentido IN ('ida','vuelta','circular')),
 estado VARCHAR(20) NOT NULL DEFAULT 'activa' CHECK(estado IN ('activa','inactiva')),
 UNIQUE(id_linea,nombre,sentido)
);
CREATE TABLE punto_ruta (                        -- trazado del recorrido
 id_punto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_ruta BIGINT NOT NULL REFERENCES ruta(id_ruta) ON DELETE CASCADE,
 orden INTEGER NOT NULL CHECK(orden>0),
 latitud NUMERIC(10,7) NOT NULL CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(10,7) NOT NULL CHECK(longitud BETWEEN -180 AND 180),
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('inicio','parada','referencia','destino')),
 descripcion VARCHAR(250),
 UNIQUE(id_ruta,orden)
);
CREATE TABLE parada (                            -- paradas que publica el mapa
 id_parada VARCHAR(60) PRIMARY KEY,               -- id que usa el backend (ej. DEMO-STOP-17-2)
 id_linea BIGINT NOT NULL REFERENCES linea(id_linea),
 nombre VARCHAR(160) NOT NULL,
 referencia VARCHAR(250) NOT NULL DEFAULT '',
 latitud NUMERIC(10,7) NOT NULL CHECK(latitud BETWEEN -90 AND 90),
 longitud NUMERIC(10,7) NOT NULL CHECK(longitud BETWEEN -180 AND 180),
 orden INTEGER NOT NULL CHECK(orden>0),
 activa BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE unidad_transporte (
 id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_linea BIGINT NOT NULL REFERENCES linea(id_linea),
 numero_interno VARCHAR(35) NOT NULL,
 placa VARCHAR(20) NOT NULL UNIQUE,
 marca VARCHAR(70), modelo VARCHAR(70),
 capacidad_maxima INTEGER NOT NULL CHECK(capacidad_maxima>0),
 estado VARCHAR(25) NOT NULL DEFAULT 'habilitada'
   CHECK(estado IN ('habilitada','deshabilitada','mantenimiento','fuera_servicio')),
 CONSTRAINT uq_unidad_linea_interno UNIQUE(id_linea,numero_interno)
);
CREATE INDEX ix_ruta_linea ON ruta(id_linea);
CREATE INDEX ix_parada_linea ON parada(id_linea,orden);
CREATE INDEX ix_unidad_linea ON unidad_transporte(id_linea);

-- Rutabol puede leer y mantener el catalogo; nunca borra lineas ni unidades.
GRANT USAGE ON SCHEMA transporte TO :"app_role";
GRANT SELECT,INSERT,UPDATE ON ALL TABLES IN SCHEMA transporte TO :"app_role";
GRANT DELETE ON punto_ruta,parada TO :"app_role";
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA transporte TO :"app_role";
COMMIT;
